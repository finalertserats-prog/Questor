#!/usr/bin/env node
// Generate server/prisma/postgres/schema.prisma from the SQLite schema.
//
// Until production switches databases, server/prisma/schema.prisma (SQLite)
// stays the single source of truth. The data model is portable — complex
// values are stored as JSON strings and nothing uses a provider-specific type —
// so the Postgres schema differs only in its datasource provider. Generating it
// rather than maintaining a second copy means the two can never drift.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'server', 'prisma', 'schema.prisma');
const target = join(root, 'server', 'prisma', 'postgres', 'schema.prisma');

const sqliteSchema = readFileSync(source, 'utf8');
const provider = /provider\s*=\s*"sqlite"/;
if (!provider.test(sqliteSchema)) {
  console.error(`Expected a "sqlite" datasource provider in ${source}; refusing to guess.`);
  process.exit(1);
}

const header = '// GENERATED by scripts/generate-postgres-schema.mjs from ../schema.prisma — do not edit by hand.\n';
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, header + sqliteSchema.replace(provider, 'provider = "postgresql"'));
console.log(`Wrote ${target}`);
